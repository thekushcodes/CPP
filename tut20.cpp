// Object-Oriented programming : A method of programming

/*
*****Why OOPS?*****
-> C++ was designed with main intention of adding object-oriented features to C language.
-> As the size of program increases, readability, maintainability and bug-free nature of program decreases.
-> This was the major problem with C which relied on functions or procedures. As a result, the possibility of not addressing the problem in an effective manner was high.
-> Also, as data was almost neglected, data security was easily compromised.
-> Using classes solves this problem by modelling program as a real-world scenario.


*****Procedure Oriented Programming vs Object Oriented Programming*****
Procedure oriented programming:
-> Consists of writing a set of instructions for the computer to follow.
-> Main focus is on functions and not on the data flow.
-> Functions can either use local or global data.
-> Data moves moves openly from function to function.
Object Oriented Programming
-> Works on the concept of CLASSES and OBJECTS. //Jb class bnaenge tb uski memory use nhi hogi, jb object bnaenge tb jakr memory use hoga.
-> A class is a template to create object.
-> Treats data as a critical element. // We can restrict usage of data and its flow.
-> Decomposes the problem in objects and builds data and functions around the objects.

*****Basic concepts in Object Oriented Programming*****
-> Classes: Basic template for creating objects.
-> Objects: Basic run time entities.
-> Data abstraction and Encapsulation: Wrapping data and functions into single unit.
-> Inheritence: Properties of one class can be inherited into others.
-> Polymorphism: Ability to take more than one form.
-> Dynamic Binding (Late Binding): Code which will execute is not known until the program runs.
-> Message Passing: Object.message(information) call format.

*****Benefits of Object Oriented Programming:*****
-> Better code reusability using objects and inheritence.
-> Principle of data hiding helps build secure systems.
-> Multiple objects can co-exist without any interference.
-> Software complexity can easily be managed.
*/
